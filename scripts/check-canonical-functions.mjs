#!/usr/bin/env node
// Canonical-function guard (review #15).
//
// PROBLEM: SQL functions are redefined wholesale across migrations
// (onboard_patient appears in 0006, 0013, 0017, 0045…). "What does prod run?"
// required reading every migration in order — and 0040/0041 resorted to
// hand-asserting "byte-identical to the deployed body" in comments.
//
// THIS SCRIPT makes the answer mechanical:
//   * For each tracked function it extracts the LAST definition across
//     supabase/migrations/*.sql (later file wins) and compares it with the
//    canonical copy in supabase/functions/<name>.sql.
//   * `node scripts/check-canonical-functions.mjs`            -> CI check (exit 1 on drift)
//   * `node scripts/check-canonical-functions.mjs --update`   -> regenerate canonical files
//
// Add a migration that redefines a function, run --update, commit both. A PR
// that changes one without the other fails the release gate.

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const TRACKED_FUNCTIONS = [
  "onboard_patient",
  "allocate_file_number",
  "write_audit_entry_atomic",
  "write_audit_entry",
  "stage_billing_export_items",
  "void_clinical_note",
  "update_patient_bundle",
  "current_app_role",
  "prevent_finalised_clinical_note_mutation",
  "prevent_consent_record_mutation",
];

const MIGRATIONS_DIR = resolve(process.cwd(), "supabase/migrations");
const CANONICAL_DIR = resolve(process.cwd(), "supabase/functions");
const UPDATE = process.argv.includes("--update");

function normalize(sql) {
  return sql.replace(/\r\n/g, "\n").trimEnd() + "\n";
}

// Extract `create or replace function [public.]<name>(...) ... $tag$ body $tag$;`
// starting at `startIndex`. Handles arbitrary dollar-quote tags ($$, $function$…).
function extractFunction(sql, startIndex) {
  const tagMatch = /as\s+(\$[a-zA-Z_]*\$)/i.exec(sql.slice(startIndex));
  if (!tagMatch) return null;
  const tag = tagMatch[1];
  const bodyStart = startIndex + tagMatch.index + tagMatch[0].length;
  const closeIndex = sql.indexOf(tag, bodyStart);
  if (closeIndex === -1) return null;
  const semi = sql.indexOf(";", closeIndex + tag.length);
  if (semi === -1) return null;
  return sql.slice(startIndex, semi + 1);
}

function lastDefinition(name) {
  const files = readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith(".sql")).sort();
  let found = null;
  for (const file of files) {
    const sql = readFileSync(join(MIGRATIONS_DIR, file), "utf8");
    const re = new RegExp(
      String.raw`create\s+or\s+replace\s+function\s+(?:public\.)?${name}\s*\(`,
      "gi"
    );
    let m;
    while ((m = re.exec(sql)) !== null) {
      const def = extractFunction(sql, m.index);
      if (def) found = { file, definition: normalize(def) };
    }
  }
  return found;
}

function canonicalContent(name, found) {
  return (
    `-- AUTO-GENERATED by scripts/check-canonical-functions.mjs — do not edit by hand.\n` +
    `-- Canonical definition of public.${name} as of migration ${found.file}.\n` +
    `-- Regenerate after adding a migration that redefines it:\n` +
    `--   node scripts/check-canonical-functions.mjs --update\n\n` +
    found.definition
  );
}

let failures = 0;
if (!existsSync(CANONICAL_DIR)) mkdirSync(CANONICAL_DIR, { recursive: true });

for (const name of TRACKED_FUNCTIONS) {
  const found = lastDefinition(name);
  if (!found) {
    console.error(`MISSING: no migration defines ${name}`);
    failures++;
    continue;
  }
  const canonicalPath = join(CANONICAL_DIR, `${name}.sql`);
  const expected = canonicalContent(name, found);

  if (UPDATE) {
    writeFileSync(canonicalPath, expected, "utf8");
    console.log(`updated  supabase/functions/${name}.sql  (from ${found.file})`);
    continue;
  }

  if (!existsSync(canonicalPath)) {
    console.error(`DRIFT: supabase/functions/${name}.sql missing (latest definition in ${found.file}). Run with --update.`);
    failures++;
    continue;
  }
  const actual = normalize(readFileSync(canonicalPath, "utf8"));
  if (actual !== normalize(expected)) {
    console.error(`DRIFT: supabase/functions/${name}.sql does not match the latest migration (${found.file}). Run with --update and commit.`);
    failures++;
  } else {
    console.log(`ok       ${name}  (${found.file})`);
  }
}

if (failures > 0) {
  console.error(`\n${failures} canonical-function problem(s).`);
  process.exit(1);
}
console.log("\nAll canonical function definitions match the migrations.");
